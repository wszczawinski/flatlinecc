// Package fields names data field and page types used in DISPLAY_CFG.
// Based on https://gist.github.com/Intyre/aefc6cced18f0610df57adcb70a11453,
// plus IDs observed on a ROAM v1.
package fields

import (
	"fmt"
	"maps"
	"slices"
)

// Name returns a display name for a field type.
func Name(id uint16) string {
	if name, ok := names[id]; ok {
		return name
	}
	return fmt.Sprintf("Field %d", id)
}

// PageName returns a display name for a page type.
func PageName(t uint8) string {
	if name, ok := pageNames[t]; ok {
		return name
	}
	return fmt.Sprintf("Page type %d", t)
}

// IDs returns all known field types in ascending order.
func IDs() []uint16 {
	return slices.Sorted(maps.Keys(names))
}

